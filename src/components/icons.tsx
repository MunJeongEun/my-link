interface PlatformIconProps extends LucideProps {
  name?: string;
}

export function PlatformIcon({ name, className = "w-5 h-5", ...props }: PlatformIconProps) {
  const iconKey = name?.toLowerCase() || "globe";

  switch (iconKey) {
    case "github":
      return <GithubIcon className={className} {...(props as React.SVGProps<SVGSVGElement>)} />;
    case "velog":
      return <BookOpen className={className} {...props} />;
    case "linkedin":
      return <LinkedinIcon className={className} {...(props as React.SVGProps<SVGSVGElement>)} />;
    case "youtube":
      return <YoutubeIcon className={className} {...(props as React.SVGProps<SVGSVGElement>)} />;
    case "instagram":
      return <InstagramIcon className={className} {...(props as React.SVGProps<SVGSVGElement>)} />;
    case "code":
    case "portfolio":
      return <Code2 className={className} {...props} />;
    case "mail":
    case "email":
      return <Mail className={className} {...props} />;
    case "globe":
    default:
      return <Globe className={className} {...props} />;
  }
}
